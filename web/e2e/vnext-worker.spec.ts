import fs from 'node:fs';
import path from 'node:path';
import { test, expect } from '@playwright/test';
const root = process.env.VNEXT_BROWSER_FIXTURES;
if (!root || !path.isAbsolute(root)) throw new Error('owned_worker_snapshots_required');
const home = JSON.parse(fs.readFileSync(path.join(root, 'home.json'), 'utf8'));
const detail = JSON.parse(fs.readFileSync(path.join(root, 'detail.json'), 'utf8'));
const revision = detail.history[0];
test('actual worker journal revision reaches the two-block page and full dated history', async ({ page }, testInfo) => {
  await page.goto('/');
  const visible = page.getByTestId('vnext-home').filter({ visible: true });
  await expect(visible).toHaveCount(1); await expect(visible.locator(':scope > section')).toHaveCount(2);
  await expect(page.getByTestId('vnext-member')).toHaveCount(home.members.length);
  await expect(page.getByText('研究條件符合', { exact: true })).toHaveCount(0);
  const card = page.getByTestId('vnext-member').filter({ has: page.getByRole('link', { name: '2409', exact: true }) });
  await expect(card).toHaveCount(1);
  await expect(card.getByRole('link', { name: '2409', exact: true })).toHaveAttribute('href', `/stock/2409?vnextRevision=${revision.revisionId}`);
  await card.getByRole('link', { name: '2409', exact: true }).click();
  await expect(page.getByTestId('vnext-detail')).toBeVisible();
  for (const section of Object.values(revision.content.sections) as Array<{ text: string }>) await expect(page.getByText(section.text, { exact: true })).toBeVisible();
  await expect(page.getByRole('table')).toContainText('0.5 ratio');
  await expect(page.getByRole('table')).toContainText(revision.content.claims[0].text);
  await expect(page.getByText(`原始發布時間：${revision.publishedAt}`, { exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: revision.publishedAt, exact: true })).toHaveAttribute('href', `/stock/2409?vnextRevision=${revision.revisionId}`);
  await expect(page.getByText(/valuation_assumptions_unavailable/)).toBeVisible();
  const bounds = await page.evaluate(() => ({ full: document.documentElement.scrollWidth, view: innerWidth }));
  expect(bounds.full).toBeLessThanOrEqual(bounds.view + 1);
  await page.screenshot({ path: testInfo.outputPath('actual-worker-revision.png'), fullPage: true });
});
